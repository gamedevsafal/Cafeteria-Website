import mongoose from "mongoose";

const OrderItemSchema = new mongoose.Schema(
  {
    menuId: { type: mongoose.Schema.Types.ObjectId, ref: "MenuItem" },
    name: { type: String, required: true },   // snapshot, survives menu edits
    price: { type: Number, required: true, min: 0 },
    qty: { type: Number, required: true, min: 1 },
    note: { type: String, default: "" }
  },
  { _id: false }
);

const STATUSES = [
  "pending",     // just received
  "confirmed",   // kitchen has accepted it
  "preparing",   // being cooked
  "ready",       // bagged, waiting for pickup
  "completed",   // collected
  "cancelled"
];

const OrderSchema = new mongoose.Schema(
  {
    // ref is generated by the pre-save hook below, which runs AFTER validation,
    // so it must not be marked required here or every create() fails.
    ref: { type: String, unique: true, index: true },

    type: { type: String, enum: ["mess", "catering"], default: "mess" },
    // Pickup at a mess counter, or home delivery inside Gwalior
    fulfilment: { type: String, enum: ["pickup", "delivery"], default: "pickup" },
    deliveryAddress: { type: String, default: "" },
    deliveryFee: { type: Number, default: 0 },
    mess: { type: String, enum: ["divya-kitchen", "digital-bharat", "all"], default: "divya-kitchen" },

    customer: {
      name: { type: String, required: true, trim: true },
      phone: { type: String, required: true, trim: true },
      email: { type: String, default: "", trim: true, lowercase: true },
      address: { type: String, default: "", trim: true }
    },

    people: { type: Number, default: 1, min: 1 },
    eventType: { type: String, default: "" },   // marriage, birthday, corporate...
    eventDate: { type: Date },
    slot: { type: String, default: "" },        // mess orders: "13:00"
    notes: { type: String, default: "" },

    items: { type: [OrderItemSchema], default: [] },
    subtotal: { type: Number, default: 0 },
    serviceFee: { type: Number, default: 0 },
    total: { type: Number, default: 0 },

    // Stripe plugs in here later: create a PaymentIntent on the order and
    // set status to "paid" from the webhook.
    payment: {
      status: { type: String, enum: ["unpaid", "pending", "paid", "refunded"], default: "unpaid" },
      method: { type: String, enum: ["pickup", "stripe"], default: "pickup" },
      stripeSessionId: { type: String, default: "" },
      paidAt: { type: Date }
    },

    status: { type: String, enum: STATUSES, default: "pending", index: true },
    statusNote: { type: String, default: "" },
    history: [
      {
        at: { type: Date, default: Date.now },
        status: String,
        by: String
      }
    ],

    source: { type: String, default: "web" }
  },
  { timestamps: true }
);

OrderSchema.index({ createdAt: -1, status: 1 });
OrderSchema.index({ "customer.phone": 1 });

OrderSchema.pre("save", function (next) {
  if (this.isNew) {
    // CT-YYMMDD-XXXX, readable over the phone and easy to eyeball
    const d = new Date();
    const stamp =
      String(d.getFullYear()).slice(2) +
      String(d.getMonth() + 1).padStart(2, "0") +
      String(d.getDate()).padStart(2, "0");
    const rand = Math.random().toString(36).slice(2, 6).toUpperCase();
    this.ref = `DC-${stamp}-${rand}`;
    this.history.push({ status: "pending", by: "customer" });
  }
  next();
});

export const Order = mongoose.model("Order", OrderSchema);
export { STATUSES };
